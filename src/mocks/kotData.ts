export type KotOrderType = 'DINE IN' | 'PARCEL' | 'DELIVERY' | 'PICK UP' | 'OTHER'
export type KotStatus = 'Used In Bill' | 'Pending' | 'Cancelled'

export interface KotRow {
  id: string
  kotId: number
  orderType: KotOrderType
  customerName: string
  customerPhone: string
  itemCount: number
  items: string
  status: KotStatus
  billPrintDate: string
  completeDuration: string
  created: string
  modified?: boolean
}

/** Parse display timestamps like "6 Aug 2026 14:32:10". */
export function parseKotDate(value: string): Date | null {
  if (!value || value === '--') return null
  const match = value.match(
    /^(\d{1,2})\s+(\w{3})\s+(\d{4})\s+(\d{2}):(\d{2}):(\d{2})$/,
  )
  if (!match) return null
  const months: Record<string, number> = {
    Jan: 0,
    Feb: 1,
    Mar: 2,
    Apr: 3,
    May: 4,
    Jun: 5,
    Jul: 6,
    Aug: 7,
    Sep: 8,
    Oct: 9,
    Nov: 10,
    Dec: 11,
  }
  const month = months[match[2]]
  if (month === undefined) return null
  return new Date(
    Number(match[3]),
    month,
    Number(match[1]),
    Number(match[4]),
    Number(match[5]),
    Number(match[6]),
  )
}

